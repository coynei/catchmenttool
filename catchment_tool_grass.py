class CatchmentTool(QgsProcessingAlgorithm):

    def initAlgorithm(self, config: Optional[dict[str, Any]] = None):
        self.addParameter(QgsProcessingParameterCrs('crs', 'CRS', defaultValue='EPSG:32736'))
        self.addParameter(QgsProcessingParameterRasterLayer('dem', 'DEM', defaultValue=None))
        self.addParameter(QgsProcessingParameterExtent('extent', 'EXTENT', defaultValue=None))
        self.addParameter(QgsProcessingParameterNumber('order', 'ORDER', type=QgsProcessingParameterNumber.Integer, minValue=1, defaultValue=5))
        self.addParameter(QgsProcessingParameterPoint('road__start_point', 'ROAD  START POINT', defaultValue=None))
        self.addParameter(QgsProcessingParameterVectorLayer('road_alignment', 'ROAD ALIGNMENT', types=[QgsProcessing.TypeVectorLine], defaultValue=None))
        self.addParameter(QgsProcessingParameterFolderDestination('OutputFolder', 'Output folder', createByDefault=True, defaultValue=None))
        self.addParameter(QgsProcessingParameterFeatureSink('OutletPointsWithCost', 'OUTLET POINTS WITH COST', type=QgsProcessing.TypeVectorAnyGeometry, createByDefault=True, supportsAppend=True, defaultValue=None))
        self.addParameter(QgsProcessingParameterFeatureSink('NamedOutletPoints', 'Named Outlet Points', type=QgsProcessing.TypeVectorAnyGeometry, createByDefault=True, supportsAppend=True, defaultValue=None))
        self.addParameter(QgsProcessingParameterFeatureSink('Chainages', 'CHAINAGES', type=QgsProcessing.TypeVectorLine, createByDefault=True, defaultValue=None))
        self.addParameter(QgsProcessingParameterVectorDestination('Channels', 'Channels', type=QgsProcessing.TypeVectorLine, createByDefault=True, defaultValue=None))
        self.addParameter(QgsProcessingParameterRasterDestination('My_filled_dem', 'MY_FILLED_DEM', createByDefault=True, defaultValue=None))
        self.addParameter(QgsProcessingParameterRasterDestination('Strahler', 'Strahler', createByDefault=True, defaultValue=None))

    def processAlgorithm(self, parameters: dict[str, Any], context: QgsProcessingContext, model_feedback: QgsProcessingFeedback) -> dict[str, Any]:
        # Use a multi-step feedback, so that individual child algorithm progress reports are adjusted for the
        # overall progress through the model
        feedback = QgsProcessingMultiStepFeedback(12, model_feedback)
        results = {}
        outputs = {}

        # QGIS has used both grass: and grass7: algorithm ID prefixes across
        # releases. Resolve the installed ID instead of hard-coding one version.
        def grass_algorithm_id(module_name: str) -> str:
            registry = QgsApplication.processingRegistry()
            for prefix in ('grass:', 'grass7:'):
                candidate = prefix + module_name
                if registry.algorithmById(candidate) is not None:
                    return candidate
            raise QgsProcessingException(
                f"Required GRASS Processing algorithm '{module_name}' is not available. "
                "Enable the GRASS provider in QGIS and check that GRASS GIS is installed."
            )

        # Clip raster by extent
        alg_params = {
            'DATA_TYPE': 0,  # Use Input Layer Data Type
            'EXTRA': None,
            'INPUT': parameters['dem'],
            'NODATA': None,
            'OPTIONS': None,
            'OVERCRS': False,
            'PROJWIN': parameters['extent'],
            'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['ClipRasterByExtent'] = processing.run('gdal:cliprasterbyextent', alg_params, context=context, feedback=feedback, is_child_algorithm=True)

        feedback.setCurrentStep(1)
        if feedback.isCanceled():
            return {}

        # Warp (reproject)
        alg_params = {
            'DATA_TYPE': 0,  # Use Input Layer Data Type
            'EXTRA': None,
            'INPUT': outputs['ClipRasterByExtent']['OUTPUT'],
            'MULTITHREADING': False,
            'NODATA': None,
            'OPTIONS': None,
            'RESAMPLING': 0,  # Nearest Neighbour
            'SOURCE_CRS': None,
            'TARGET_CRS': parameters['crs'],
            'TARGET_EXTENT': None,
            'TARGET_EXTENT_CRS': None,
            'TARGET_RESOLUTION': None,
            'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['WarpReproject'] = processing.run('gdal:warpreproject', alg_params, context=context, feedback=feedback, is_child_algorithm=True)

        feedback.setCurrentStep(2)
        if feedback.isCanceled():
            return {}

        # Fill nodata
        alg_params = {
            'BAND': 1,
            'DISTANCE': 10,
            'EXTRA': None,
            'INPUT': outputs['WarpReproject']['OUTPUT'],
            'ITERATIONS': 0,
            'MASK_LAYER': None,
            'NO_MASK': False,
            'OPTIONS': None,
            'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['FillNodata'] = processing.run('gdal:fillnodata', alg_params, context=context, feedback=feedback, is_child_algorithm=True)

        feedback.setCurrentStep(3)
        if feedback.isCanceled():
            return {}

        # GRASS r.fill.dir: create a depressionless DEM and flow-direction raster.
        # GRASS r.fill.dir uses its own depression-filling method.
        alg_params = {
            'input': outputs['FillNodata']['OUTPUT'],
            'format': 0,  # GRASS direction format
            '-f': False,
            'output': parameters['My_filled_dem'],
            'direction': QgsProcessing.TEMPORARY_OUTPUT,
            'areas': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['FillSinksGRASS'] = processing.run(
            grass_algorithm_id('r.fill.dir'), alg_params, context=context,
            feedback=feedback, is_child_algorithm=True
        )
        results['My_filled_dem'] = outputs['FillSinksGRASS']['output']

        feedback.setCurrentStep(4)
        if feedback.isCanceled():
            return {}

        # GRASS r.watershed supplies accumulation and drainage direction for outlets.
        # Use single-flow (D8) direction so the drainage raster can drive r.water.outlet.
        alg_params = {
            'elevation': outputs['FillSinksGRASS']['output'],
            'depression': None,
            'flow': None,
            'disturbed_land': None,
            'blocking': None,
            'threshold': max(1, int(parameters['order']),),
            'max_slope_length': None,
            'convergence': 5,
            'memory': 300,
            '-s': True,
            '-m': False,
            '-4': False,
            '-a': True,
            '-b': True,
            'accumulation': QgsProcessing.TEMPORARY_OUTPUT,
            'drainage': QgsProcessing.TEMPORARY_OUTPUT,
            'basin': QgsProcessing.TEMPORARY_OUTPUT,
            'stream': QgsProcessing.TEMPORARY_OUTPUT,
            'half_basin': QgsProcessing.TEMPORARY_OUTPUT,
            'length_slope': QgsProcessing.TEMPORARY_OUTPUT,
            'slope_steepness': QgsProcessing.TEMPORARY_OUTPUT,
            'tci': QgsProcessing.TEMPORARY_OUTPUT,
            'spi': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['GrassWatershed'] = processing.run(
            grass_algorithm_id('r.watershed'), alg_params, context=context,
            feedback=feedback, is_child_algorithm=True
        )

        feedback.setCurrentStep(5)
        if feedback.isCanceled():
            return {}

        # Extract stream network with GRASS. The threshold is a flow-accumulation
        # cell count; as in the previous tool, it is controlled by the ORDER input.
        alg_params = {
            'elevation': outputs['FillSinksGRASS']['output'],
            'accumulation': outputs['GrassWatershed']['accumulation'],
            'depression': None,
            'threshold': max(1, float(parameters['order'])),
            'mexp': 0,
            'stream_length': 0,
            'd8cut': None,
            'memory': 300,
            'stream_raster': QgsProcessing.TEMPORARY_OUTPUT,
            'stream_vector': parameters['Channels'],
            'direction': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['GrassStreamExtract'] = processing.run(
            grass_algorithm_id('r.stream.extract'), alg_params, context=context,
            feedback=feedback, is_child_algorithm=True
        )
        results['Channels'] = outputs['GrassStreamExtract']['stream_vector']

        # GRASS r.stream.order is an optional GRASS add-on in some installations.
        # Fail with a clear message if this GRASS add-on is unavailable.
        try:
            stream_order_algorithm_id = grass_algorithm_id('r.stream.order')
        except QgsProcessingException:
            raise QgsProcessingException(
                "The GRASS algorithm 'r.stream.order' is not available in this QGIS/GRASS installation. "
                "Install/enable the GRASS r.stream.order add-on, then retry."
            )
        outputs['StrahlerOrder'] = processing.run(
            stream_order_algorithm_id,
            {
                'stream_rast': outputs['GrassStreamExtract']['stream_raster'],
                'direction': outputs['GrassStreamExtract']['direction'],
                'elevation': outputs['FillSinksGRASS']['output'],
                'accumulation': outputs['GrassWatershed']['accumulation'],
                'stream_vect': QgsProcessing.TEMPORARY_OUTPUT,
                'strahler': parameters['Strahler'],
                'horton': QgsProcessing.TEMPORARY_OUTPUT,
                'shreve': QgsProcessing.TEMPORARY_OUTPUT,
                'hack': QgsProcessing.TEMPORARY_OUTPUT,
                'topo': QgsProcessing.TEMPORARY_OUTPUT,
                'memory': 300,
                '-z': False,
                '-m': False,
                '-a': False
            }, context=context, feedback=feedback, is_child_algorithm=True
        )
        results['Strahler'] = outputs['StrahlerOrder']['strahler']

        feedback.setCurrentStep(6)
        if feedback.isCanceled():
            return {}

        # Line intersections
        alg_params = {
            'INPUT': parameters['road_alignment'],
            'INPUT_FIELDS': [''],
            'INTERSECT': outputs['GrassStreamExtract']['stream_vector'],
            'INTERSECT_FIELDS': [''],
            'INTERSECT_FIELDS_PREFIX': None,
            'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['LineIntersections'] = processing.run('native:lineintersections', alg_params, context=context, feedback=feedback, is_child_algorithm=True)

        feedback.setCurrentStep(7)
        if feedback.isCanceled():
            return {}

        # Name outlet points
        alg_params = {
            'FIELD_LENGTH': 10,
            'FIELD_NAME': 'name',
            'FIELD_PRECISION': 0,
            'FIELD_TYPE': 2,  # Text (string)
            'FORMULA': "concat('outl_',@row_number)",
            'INPUT': outputs['LineIntersections']['OUTPUT'],
            'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['NameOutletPoints'] = processing.run('native:fieldcalculator', alg_params, context=context, feedback=feedback, is_child_algorithm=True)

        feedback.setCurrentStep(8)
        if feedback.isCanceled():
            return {}

        # Retain only the name of the outlet point
        alg_params = {
            'FIELDS': ['name'],
            'INPUT': outputs['NameOutletPoints']['OUTPUT'],
            'OUTPUT': parameters['NamedOutletPoints']
        }
        outputs['RetainOnlyTheNameOfTheOutletPoint'] = processing.run('native:retainfields', alg_params, context=context, feedback=feedback, is_child_algorithm=True)
        results['NamedOutletPoints'] = outputs['RetainOnlyTheNameOfTheOutletPoint']['OUTPUT']

        feedback.setCurrentStep(9)
        if feedback.isCanceled():
            return {}

        # Shortest path (point to layer)
        alg_params = {
            'DEFAULT_DIRECTION': 2,  # Both directions
            'DEFAULT_SPEED': 50,
            'DIRECTION_FIELD': None,
            'END_POINTS': outputs['RetainOnlyTheNameOfTheOutletPoint']['OUTPUT'],
            'INPUT': parameters['road_alignment'],
            'POINT_TOLERANCE': None,
            'SPEED_FIELD': None,
            'START_POINT': parameters['road__start_point'],
            'STRATEGY': 0,  # Shortest
            'TOLERANCE': 0,
            'VALUE_BACKWARD': None,
            'VALUE_BOTH': None,
            'VALUE_FORWARD': None,
            # Keep the numeric shortest-path result temporarily for calculations.
            'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['ShortestPathPointToLayer'] = processing.run('native:shortestpathpointtolayer', alg_params, context=context, feedback=feedback, is_child_algorithm=True)

        # Format the chainage cost as text: KM 0 + 000.
        outputs['ChainagesFormattedTemp'] = processing.run(
            'native:fieldcalculator',
            {
                'FIELD_LENGTH': 30,
                'FIELD_NAME': 'cost_formatted',
                'FIELD_PRECISION': 0,
                'FIELD_TYPE': 2,  # Text
                'FORMULA': "with_variable('m', round(\"cost\"), concat('KM ', to_string(floor(@m / 1000)), ' + ', lpad(to_string(@m - floor(@m / 1000) * 1000), 3, '0')))",
                'INPUT': outputs['ShortestPathPointToLayer']['OUTPUT'],
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            }, context=context, feedback=feedback, is_child_algorithm=True
        )
        outputs['ChainagesNoNumericCost'] = processing.run(
            'native:deletecolumn',
            {
                'COLUMN': ['cost'],
                'INPUT': outputs['ChainagesFormattedTemp']['OUTPUT'],
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            }, context=context, feedback=feedback, is_child_algorithm=True
        )
        outputs['ChainagesFinal'] = processing.run(
            'native:renametablefield',
            {
                'FIELD': 'cost_formatted',
                'INPUT': outputs['ChainagesNoNumericCost']['OUTPUT'],
                'NEW_NAME': 'cost',
                'OUTPUT': parameters['Chainages']
            }, context=context, feedback=feedback, is_child_algorithm=True
        )
        results['Chainages'] = outputs['ChainagesFinal']['OUTPUT']

        feedback.setCurrentStep(10)
        if feedback.isCanceled():
            return {}

        # Set costs (Fixed expression to reference the actual output layer path/ID)
        shortest_path_output = outputs['ShortestPathPointToLayer']['OUTPUT']
        alg_params = {
            'FIELD_LENGTH': 0,
            'FIELD_NAME': 'cost',
            'FIELD_PRECISION': 0,
            'FIELD_TYPE': 0,  # Decimal (double)
            'FORMULA': f"attribute(get_feature('{shortest_path_output}', 'name', name), 'cost')",
            'INPUT': outputs['RetainOnlyTheNameOfTheOutletPoint']['OUTPUT'],
            'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
        }
        outputs['SetCosts'] = processing.run('native:fieldcalculator', alg_params, context=context, feedback=feedback, is_child_algorithm=True)

        feedback.setCurrentStep(11)
        if feedback.isCanceled():
            return {}

        # Calculate catchments from points (integrated; no external plugin call)
        # This reproduces the points_to_catchments algorithm directly in this
        # algorithm, using the existing outlet points and filled DEM.
        from qgis.core import (
            Qgis, QgsVectorLayer, QgsVectorFileWriter, QgsField, QgsProcessingUtils
        )

        # Processing outputs may be temporary layer IDs (for example
        # 'Calculated_...'), not file paths. Resolve them from the active context
        # before trying the OGR provider; opening a layer ID as a file can produce
        # a valid-looking but empty layer, which caused Outlet count=0.
        outflow_points_output = outputs['SetCosts']['OUTPUT']
        outflow_points = None
        if isinstance(outflow_points_output, QgsVectorLayer):
            outflow_points = outflow_points_output
        else:
            outflow_points = QgsProcessingUtils.mapLayerFromString(
                str(outflow_points_output), context
            )
            if outflow_points is None or not outflow_points.isValid():
                outflow_points = QgsVectorLayer(
                    str(outflow_points_output), 'outlet_points', 'ogr'
                )
        if outflow_points is None or not outflow_points.isValid():
            raise QgsProcessingException(
                'Cannot open the outlet-points output layer: '
                f'{outflow_points_output!r}.'
            )
        feedback.pushInfo(
            f"Outlet-points layer resolved: {outflow_points.name()}, "
            f"features={outflow_points.featureCount()}, "
            f"fields={[field.name() for field in outflow_points.fields()]}"
        )

        dem_path = outputs['FillSinksGRASS']['output']
        output_folder = self.parameterAsString(parameters, 'OutputFolder', context)
        os.makedirs(output_folder, exist_ok=True)

        # Ensure outlet points have a cost field. Processing outputs can be layer IDs
        # in the current QgsProcessingContext rather than filesystem paths. Resolve them
        # through QgsProcessingUtils before attempting to open them with OGR.
        cost_field_idx = outflow_points.fields().lookupField('cost')
        if cost_field_idx < 0:
            from qgis.PyQt.QtCore import QVariant

            shortest_path_output = outputs['ShortestPathPointToLayer']['OUTPUT']
            shortest_path_layer = QgsProcessingUtils.mapLayerFromString(
                str(shortest_path_output), context
            )
            if shortest_path_layer is None or not shortest_path_layer.isValid():
                shortest_path_layer = QgsVectorLayer(
                    str(shortest_path_output), 'shortest_path_costs', 'ogr'
                )

            if shortest_path_layer is None or not shortest_path_layer.isValid():
                raise QgsProcessingException(
                    "Cannot access the shortest-path output layer. The processing result "
                    f"was: {shortest_path_output!r}."
                )

            path_fields = [field.name() for field in shortest_path_layer.fields()]
            feedback.pushInfo(f"Shortest-path fields: {path_fields}")
            path_cost_idx = shortest_path_layer.fields().lookupField('cost')
            point_name_idx = outflow_points.fields().lookupField('name')
            path_name_idx = shortest_path_layer.fields().lookupField('name')

            if path_cost_idx < 0:
                raise QgsProcessingException(
                    "The shortest-path output layer is accessible but has no 'cost' field. "
                    f"Available fields: {path_fields}. Check the Chainages output schema."
                )

            # Prefer name-based matching if the shortest-path algorithm preserved names.
            costs_by_name = {}
            if path_name_idx >= 0 and point_name_idx >= 0:
                for path_feature in shortest_path_layer.getFeatures():
                    costs_by_name[str(path_feature.attribute(path_name_idx))] = (
                        path_feature.attribute(path_cost_idx)
                    )

            # The native shortestpathpointtolayer algorithm may output start/end/cost
            # rather than carrying the destination's 'name'. In that case its output
            # routes are normally returned in destination order; use positional matching
            # only when feature counts agree, and report that fallback explicitly.
            point_features = list(outflow_points.getFeatures())
            path_features = list(shortest_path_layer.getFeatures())
            costs_by_fid = {}
            if not costs_by_name and len(point_features) == len(path_features):
                feedback.pushInfo(
                    "Shortest-path output has no matching 'name' field; assigning costs "
                    "by feature order because point and route counts match."
                )
                costs_by_fid = {
                    point_features[i].id(): path_features[i].attribute(path_cost_idx)
                    for i in range(len(point_features))
                }
            elif not costs_by_name:
                raise QgsProcessingException(
                    "Cannot safely match shortest-path costs to outlet points. "
                    f"Outlet count={len(point_features)}, route count={len(path_features)}, "
                    f"shortest-path fields={path_fields}."
                )

            if not outflow_points.startEditing():
                raise QgsProcessingException(
                    "Could not edit the outlet points layer to add the missing 'cost' field."
                )
            outflow_points.addAttribute(QgsField('cost', QVariant.Double, len=20, prec=6))
            outflow_points.updateFields()
            cost_field_idx = outflow_points.fields().lookupField('cost')
            for outlet_feature in outflow_points.getFeatures():
                if costs_by_name and point_name_idx >= 0:
                    outlet_name = str(outlet_feature.attribute(point_name_idx))
                    if outlet_name in costs_by_name:
                        outflow_points.changeAttributeValue(
                            outlet_feature.id(), cost_field_idx, costs_by_name[outlet_name]
                        )
                elif outlet_feature.id() in costs_by_fid:
                    outflow_points.changeAttributeValue(
                        outlet_feature.id(), cost_field_idx, costs_by_fid[outlet_feature.id()]
                    )
            if not outflow_points.commitChanges():
                outflow_points.rollBack()
                raise QgsProcessingException(
                    "Failed to save the recovered 'cost' values to the outlet points layer."
                )

        # Create the final outlet-points output with cost stored as formatted text.
        outputs['OutletCostFormattedTemp'] = processing.run(
            'native:fieldcalculator',
            {
                'FIELD_LENGTH': 30,
                'FIELD_NAME': 'cost_formatted',
                'FIELD_PRECISION': 0,
                'FIELD_TYPE': 2,  # Text
                'FORMULA': "with_variable('m', round(\"cost\"), concat('KM ', to_string(floor(@m / 1000)), ' + ', lpad(to_string(@m - floor(@m / 1000) * 1000), 3, '0')))",
                'INPUT': outflow_points,
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            }, context=context, feedback=feedback, is_child_algorithm=True
        )
        outputs['OutletCostNoNumericCost'] = processing.run(
            'native:deletecolumn',
            {
                'COLUMN': ['cost'],
                'INPUT': outputs['OutletCostFormattedTemp']['OUTPUT'],
                'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT
            }, context=context, feedback=feedback, is_child_algorithm=True
        )
        outputs['OutletCostFinal'] = processing.run(
            'native:renametablefield',
            {
                'FIELD': 'cost_formatted',
                'INPUT': outputs['OutletCostNoNumericCost']['OUTPUT'],
                'NEW_NAME': 'cost',
                'OUTPUT': parameters['OutletPointsWithCost']
            }, context=context, feedback=feedback, is_child_algorithm=True
        )
        results['OutletPointsWithCost'] = outputs['OutletCostFinal']['OUTPUT']

        outflow_points_output = outputs['OutletCostFinal']['OUTPUT']
        outflow_points = QgsProcessingUtils.mapLayerFromString(str(outflow_points_output), context)
        if outflow_points is None or not outflow_points.isValid():
            outflow_points = QgsVectorLayer(str(outflow_points_output), 'outlet_points_formatted', 'ogr')
        if outflow_points is None or not outflow_points.isValid():
            raise QgsProcessingException('Could not reopen the formatted outlet-points output.')
        cost_field_idx = outflow_points.fields().lookupField('cost')
        if cost_field_idx < 0:
            raise QgsProcessingException('Formatted outlet-points output has no cost field.')

        total_points = outflow_points.featureCount()
        if total_points == 0:
            feedback.reportError("No outlet points were generated; no catchments were created.")
        else:
            for i, point_feature in enumerate(outflow_points.getFeatures()):
                if feedback.isCanceled():
                    return {}

                cost_value = point_feature.attribute(cost_field_idx)
                geom = point_feature.geometry()
                if geom.isNull() or geom.isEmpty():
                    feedback.reportError(
                        f"Skipping outlet feature {point_feature.id()}: empty geometry."
                    )
                    continue

                point = geom.asPoint()
                x, y = point.x(), point.y()
                feedback.pushInfo(
                    f"Creating catchment for outlet ({x:.2f}, {y:.2f}), "
                    f"cost {cost_value} — {i + 1} of {total_points}"
                )
                feedback.setProgress(70 + int((i / max(total_points, 1)) * 29))

                # Delineate each catchment using GRASS r.water.outlet and the
                # D8 drainage direction raster produced by GRASS r.watershed.
                catchment_raster = processing.run(
                    grass_algorithm_id('r.water.outlet'),
                    {
                        'input': outputs['GrassWatershed']['drainage'],
                        'coordinates': f'{x},{y}',
                        'output': QgsProcessing.TEMPORARY_OUTPUT
                    },
                    context=context, feedback=feedback, is_child_algorithm=True
                )

                catchment_polygon = processing.run(
                    'gdal:polygonize',
                    {
                        'INPUT': catchment_raster['output'],
                        'BAND': 1,
                        'FIELD': 'DN',
                        'EIGHT_CONNECTEDNESS': False,
                        'OUTPUT': QgsProcessing.TEMPORARY_OUTPUT,
                    },
                    context=context, feedback=feedback, is_child_algorithm=True
                )

                catchment_layer = QgsVectorLayer(
                    catchment_polygon['OUTPUT'], 'catchment_polygons', 'ogr'
                )
                if not catchment_layer.isValid():
                    raise QgsProcessingException(
                        f"Could not load polygonized catchment for outlet {i + 1}."
                    )

                # Add the outlet's cost to every polygon feature.
                catchment_layer.startEditing()
                catchment_layer.addAttribute(
                    QgsField('cost', outflow_points.fields().at(cost_field_idx).type(), len=30)
                )
                catchment_layer.updateFields()
                new_cost_idx = catchment_layer.fields().lookupField('cost')
                for catchment_feature in catchment_layer.getFeatures():
                    catchment_layer.changeAttributeValue(
                        catchment_feature.id(), new_cost_idx, cost_value
                    )
                if not catchment_layer.commitChanges():
                    catchment_layer.rollBack()
                    raise QgsProcessingException(
                        f"Could not write cost attribute for catchment {i + 1}."
                    )

                # GRASS r.water.outlet writes 1 for watershed cells and 0 outside.
                if catchment_layer.fields().lookupField('DN') < 0:
                    raise QgsProcessingException(
                        "Polygonized catchment has no 'DN' field."
                    )
                catchment_layer.selectByExpression('"DN" = 1')
                output_path = os.path.join(output_folder, f'area_{i + 1}.shp')
                save_result = QgsVectorFileWriter.writeAsVectorFormat(
                    catchment_layer,
                    output_path,
                    'UTF-8',
                    outflow_points.crs(),
                    'ESRI Shapefile',
                    onlySelected=True
                )
                # QGIS 3's legacy writer returns (error_code, message, ...).
                if save_result and save_result[0] != QgsVectorFileWriter.NoError:
                    raise QgsProcessingException(
                        f"Failed to save catchment {i + 1}: {save_result[1]}"
                    )

        results['OutputFolder'] = output_folder
        feedback.setProgress(100)
        return results

